// Generates tokens.css and the Apple kit's Tokens.swift from tokens.json.
//
//   node packages/theme/build.mjs           writes both
//   node packages/theme/build.mjs --check   fails if either is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const { radius, colors, opacity, shadow } = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const names = Object.keys(colors.light);
const opacities = Object.keys(opacity.light);

for (const [kind, light, dark] of [["colors", colors.light, colors.dark], ["opacity", opacity.light, opacity.dark]]) {
  const missing = Object.keys(light).filter((name) => !(name in dark));
  if (missing.length) throw new Error(`${kind}.dark is missing ${missing.join(", ")}`);
}

const indent = (lines, depth) => lines.map((line) => `${" ".repeat(depth)}${line}`).join("\n");
const theme = (mode) => [
  ...names.map((name) => `--${name}: ${colors[mode][name]};`),
  ...opacities.map((name) => `--opacity-${name}: ${opacity[mode][name]};`),
];

const css = `/* Generated by build.mjs from tokens.json. Do not edit. */

:root {
${indent(Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value}px;`), 2)}
${indent(Object.entries(shadow).map(([name, value]) => `--shadow-${name}: ${value};`), 2)}
}

/* .light keeps an element in the light scheme whatever the system's. */
:root,
.light {
${indent(theme("light"), 2)}
}

@media (prefers-color-scheme: dark) {
  :root {
${indent(theme("dark"), 4)}
  }
}
`;

const camel = (name) => name.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());
const swiftName = (name) => (name === "2xl" ? "xxl" : camel(name));
const hex = (color) => `0x${color.slice(1)}`;
const shadows = Object.entries(shadow).map(([name, value]) => [name, value.split(" ").map(parseFloat)]);
const swift = `// Generated by packages/theme/build.mjs from tokens.json. Do not edit.

import SwiftUI

enum Tokens {
${names.map((name) => `    static let ${camel(name)} = ThemeColor(light: ${hex(colors.light[name])}, dark: ${hex(colors.dark[name])})`).join("\n")}
}

/// How much of a colour or a view shows: every opacity in the apps is one of these.
enum Opacity {
${opacities.map((name) => `    static let ${camel(name)} = ThemeNumber(light: ${opacity.light[name]}, dark: ${opacity.dark[name]})`).join("\n")}
}

/// How round corners are: every radius in the apps is one of these.
enum Radius {
${Object.entries(radius).map(([name, value]) => `    static let ${swiftName(name)}: CGFloat = ${value}`).join("\n")}
}

/// A shadow's size: how far down it falls and its blur.
enum ShadowSize {
    case ${shadows.map(([name]) => name).join(", ")}

    var down: CGFloat {
        switch self {
${shadows.map(([name, [, down]]) => `        case .${name}: ${down}`).join("\n")}
        }
    }

    var blur: CGFloat {
        switch self {
${shadows.map(([name, [, , blur]]) => `        case .${name}: ${blur}`).join("\n")}
        }
    }
}
`;

const outputs = [
  [join(here, "tokens.css"), css],
  [join(root, "packages/apple/Sources/MailUI/Shared/Theme/Tokens.swift"), swift],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([path]) => path.replace(root + "/", "")).join(", ")}. Run node packages/theme/build.mjs`);
    process.exit(1);
  }
  console.log("✓ Generated tokens are up to date");
} else {
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log("✓ Wrote tokens.css and Tokens.swift");
}
