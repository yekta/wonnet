// Generates tokens.css, the Apple kit's Tokens.swift, MailPush's AccountColors.swift, the
// Android app's Tokens.kt and the desktop app's tokens.rs from tokens.json.
//
//   node packages/theme/build.mjs           writes them
//   node packages/theme/build.mjs --check   fails if one is out of date
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const { radius, colors, opacity, shadow } = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const names = Object.keys(colors.light);
const opacities = Object.keys(opacity.light);

for (const [kind, light, dark] of [["colors", colors.light, colors.dark], ["opacity", opacity.light, opacity.dark]]) {
  const missing = Object.keys(light).filter((name) => !(name in dark));
  if (missing.length) throw new Error(`${kind}.dark is missing ${missing.join(", ")}`);
}

const indent = (lines, depth) => lines.map((line) => `${" ".repeat(depth)}${line}`).join("\n");
const theme = (mode) => [
  ...names.map((name) => `--${name}: ${colors[mode][name]};`),
  ...opacities.map((name) => `--opacity-${name}: ${opacity[mode][name]};`),
];

const css = `/* Generated by build.mjs from tokens.json. Do not edit. */

:root {
${indent(Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value}px;`), 2)}
${indent(Object.entries(shadow).map(([name, value]) => `--shadow-${name}: ${value};`), 2)}
}

/* .light keeps an element in the light scheme whatever the system's. */
:root,
.light {
${indent(theme("light"), 2)}
}

@media (prefers-color-scheme: dark) {
  :root {
${indent(theme("dark"), 4)}
  }
}
`;

const camel = (name) => name.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());
const swiftName = (name) => (name === "2xl" ? "xxl" : camel(name));
const hex = (color) => `0x${color.slice(1)}`;
const shadows = Object.entries(shadow).map(([name, value]) => [name, value.split(" ").map(parseFloat)]);
const swift = `// Generated by packages/theme/build.mjs from tokens.json. Do not edit.

import SwiftUI

enum Tokens {
${names.map((name) => `    static let ${camel(name)} = ThemeColor(light: ${hex(colors.light[name])}, dark: ${hex(colors.dark[name])})`).join("\n")}
}

/// How much of a colour or a view shows: every opacity in the apps is one of these.
enum Opacity {
${opacities.map((name) => `    static let ${camel(name)} = ThemeNumber(light: ${opacity.light[name]}, dark: ${opacity.dark[name]})`).join("\n")}
}

/// How round corners are: every radius in the apps is one of these.
enum Radius {
${Object.entries(radius).map(([name, value]) => `    static let ${swiftName(name)}: CGFloat = ${value}`).join("\n")}
}

/// A shadow's size: how far down it falls and its blur.
enum ShadowSize {
    case ${shadows.map(([name]) => name).join(", ")}

    var down: CGFloat {
        switch self {
${shadows.map(([name, [, down]]) => `        case .${name}: ${down}`).join("\n")}
        }
    }

    var blur: CGFloat {
        switch self {
${shadows.map(([name, [, , blur]]) => `        case .${name}: ${blur}`).join("\n")}
        }
    }
}
`;

const accounts = names.filter((name) => /^account-\d+$/.test(name));
const accountColors = `// Generated by packages/theme/build.mjs from tokens.json. Do not edit.

/// The account colours in the light scheme, and the text drawn on them, for the notification
/// extension, which has no \`Tokens\`.
public enum AccountColors {
    public static let light: [UInt32] = [${accounts.map((name) => hex(colors.light[name])).join(", ")}]
    public static let foreground: UInt32 = ${hex(colors.light["primary-foreground"])}
}
`;

const kotlinName = (name) => (name === "2xl" ? "xxl" : camel(name));
const kotlin = `// Generated by packages/theme/build.mjs from tokens.json. Do not edit.

package app.wonnet.theme

import androidx.compose.ui.unit.dp

object Tokens {
${names.map((name) => `    val ${camel(name)} = ThemeColor(light = ${hex(colors.light[name])}, dark = ${hex(colors.dark[name])})`).join("\n")}
}

/** How much of a colour or a view shows: every opacity in the app is one of these. */
object Opacity {
${opacities.map((name) => `    val ${camel(name)} = ThemeNumber(light = ${opacity.light[name]}f, dark = ${opacity.dark[name]}f)`).join("\n")}
}

/** How round corners are: every radius in the app is one of these. */
object Radius {
${Object.entries(radius).map(([name, value]) => `    val ${kotlinName(name)} = ${value}.dp`).join("\n")}
}

/** A shadow's size: how far down it falls and its blur. */
enum class ShadowSize(val down: Float, val blur: Float) {
${shadows.map(([name, [, down, blur]]) => `    ${name.toUpperCase()}(${down}f, ${blur}f)`).join(",\n")},
}
`;

const constant = (name) => (name === "2xl" ? "XXL" : name.replace(/-/g, "_").toUpperCase());
const rust = `// Generated by packages/theme/build.mjs from tokens.json. Do not edit.

use super::{ThemeColor, ThemeNumber};

${names.map((name) => `pub const ${constant(name)}: ThemeColor = ThemeColor { light: ${hex(colors.light[name])}, dark: ${hex(colors.dark[name])} };`).join("\n")}

/// How much of a colour or a view shows: every opacity in the app is one of these.
pub mod opacity {
    use super::ThemeNumber;

${opacities.map((name) => `    pub const ${constant(name)}: ThemeNumber = ThemeNumber { light: ${opacity.light[name]}, dark: ${opacity.dark[name]} };`).join("\n")}
}

/// How round corners are: every radius in the app is one of these.
pub mod radius {
${Object.entries(radius).map(([name, value]) => `    pub const ${constant(name)}: f32 = ${value}.0;`).join("\n")}
}

/// A shadow's size: how far down it falls and its blur.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ShadowSize {
${shadows.map(([name]) => `    ${name[0].toUpperCase()}${name.slice(1)},`).join("\n")}
}

impl ShadowSize {
    pub fn down(self) -> f32 {
        match self {
${shadows.map(([name, [, down]]) => `            Self::${name[0].toUpperCase()}${name.slice(1)} => ${down}.0,`).join("\n")}
        }
    }

    pub fn blur(self) -> f32 {
        match self {
${shadows.map(([name, [, , blur]]) => `            Self::${name[0].toUpperCase()}${name.slice(1)} => ${blur}.0,`).join("\n")}
        }
    }
}
`;

const outputs = [
  [join(here, "tokens.css"), css],
  [join(root, "packages/apple/Sources/MailUI/Shared/Theme/Tokens.swift"), swift],
  [join(root, "packages/apple/Sources/MailPush/AccountColors.swift"), accountColors],
  [join(root, "apps/android/app/src/main/java/app/wonnet/theme/Tokens.kt"), kotlin],
  [join(root, "apps/gpui/src/theme/tokens.rs"), rust],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([path]) => path.replace(root + "/", "")).join(", ")}. Run node packages/theme/build.mjs`);
    process.exit(1);
  }
  console.log("✓ Generated tokens are up to date");
} else {
  for (const [path, text] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  console.log("✓ Wrote tokens.css, Tokens.swift, AccountColors.swift, Tokens.kt and tokens.rs");
}
